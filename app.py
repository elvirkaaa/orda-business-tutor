def read_md_file(filename, folder="materials"):
    if not filename:
        return None
    path = os.path.join(folder, filename)
    if not os.path.isfile(path):
        return None
    with open(path, encoding="utf-8", errors="ignore") as f:
        txt = f.read().strip()
    return txt if txt else None

def find_snippet(md_text, query):
    if not md_text:
        return None
    parts = [p.strip() for p in re.split(r"\n\s*\n", md_text) if len(p.strip()) > 15]
    if not parts:
        return md_text[:200]
    words = set(re.findall(r"\w{3,}", query.lower()))
    best = max(parts, key=lambda p: sum(w in p.lower() for w in words))
    return best[:200]

def get_reply(subj, case_name, q):
    base_guide = CATALOG[subj]["cases"][case_name][q]
    target_md = CATALOG[subj]["md_file"]
    md_content = read_md_file(target_md)

    if md_content:
        snip = find_snippet(md_content, f"{case_name} {q}")
        suffix = " (общий материал платформы)" if target_md == "orda_business.md" else ""
        source_line = f"\n\n> 📎 Файл `{target_md}`{suffix}: {snip}…"
    else:
        source_line = ""

    return f"**{case_name}**\n\n{base_guide}{source_line}"

